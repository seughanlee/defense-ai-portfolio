"""Tiny synthetic dataset in MVTec layout, for smoke tests only.

Results on this data say nothing about real detection performance. It exists so that the full pipeline
(scan -> fit -> threshold -> evaluate -> visualise) can run without downloading MVTec AD, including in CI.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
from PIL import Image

SYNTHETIC_CATEGORY = "synthetic_part"


def _base_part(rng: np.random.Generator, size: int) -> np.ndarray:
    """A grey disc ("part") with a hole, on a dark textured background, slightly jittered per sample."""
    yy, xx = np.mgrid[0:size, 0:size].astype(np.float32)
    cx, cy = size / 2 + rng.normal(0, 1.0, 2)
    r = np.hypot(xx - cx, yy - cy)
    img = 40 + rng.normal(0, 4, (size, size))
    ring = (r < size * 0.38) & (r > size * 0.14)
    img[ring] = 150 + 10 * np.cos(r[ring] / 3.0) + rng.normal(0, 3, ring.sum())
    return img


def _add_defect(rng: np.random.Generator, img: np.ndarray, kind: str) -> np.ndarray:
    size = img.shape[0]
    mask = np.zeros_like(img, dtype=bool)
    yy, xx = np.mgrid[0:size, 0:size]
    c = size / 2
    if kind == "scratch":
        angle = rng.uniform(0, np.pi)
        offset = rng.uniform(size * 0.18, size * 0.32)
        px, py = c + offset * np.cos(angle), c + offset * np.sin(angle)
        dx, dy = -np.sin(angle), np.cos(angle)
        t = (xx - px) * dx + (yy - py) * dy
        d = np.abs((xx - px) * np.cos(angle) + (yy - py) * np.sin(angle))
        mask = (d < 1.5) & (np.abs(t) < size * 0.08)
        img[mask] = 235
    elif kind == "spot":
        angle = rng.uniform(0, 2 * np.pi)
        offset = rng.uniform(size * 0.18, size * 0.32)
        px, py = c + offset * np.cos(angle), c + offset * np.sin(angle)
        mask = np.hypot(xx - px, yy - py) < size * 0.04
        img[mask] = 20
    else:
        raise ValueError(kind)
    return mask


def make_synthetic_dataset(
    root: str | Path,
    n_train: int = 20,
    n_test_good: int = 6,
    n_test_defect: int = 6,
    size: int = 96,
    seed: int = 0,
) -> Path:
    """Write a synthetic category under ``root`` and return the category path."""
    rng = np.random.default_rng(seed)
    base = Path(root) / SYNTHETIC_CATEGORY

    def save(arr: np.ndarray, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8)).convert("RGB").save(path)

    for i in range(n_train):
        save(_base_part(rng, size), base / "train" / "good" / f"{i:03d}.png")
    for i in range(n_test_good):
        save(_base_part(rng, size), base / "test" / "good" / f"{i:03d}.png")
    for kind in ("scratch", "spot"):
        for i in range(n_test_defect // 2):
            img = _base_part(rng, size)
            mask = _add_defect(rng, img, kind)
            save(img, base / "test" / kind / f"{i:03d}.png")
            mask_path = base / "ground_truth" / kind / f"{i:03d}_mask.png"
            mask_path.parent.mkdir(parents=True, exist_ok=True)
            Image.fromarray(mask.astype(np.uint8) * 255).save(mask_path)
    (base / "SYNTHETIC_DATA_NOT_FOR_PERFORMANCE_CLAIMS.txt").write_text(
        "Generated by ml/datasets/synthetic.py for smoke tests. Not a benchmark.\n", encoding="utf-8"
    )
    return base
